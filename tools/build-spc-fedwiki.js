#!/usr/bin/env node
/**
 * Build the FedWiki importer bundle for the Process Behavior Charts pages.
 *
 *     node tools/build-spc-fedwiki.js
 *
 * Why this exists instead of one call to md-to-fedwiki-page.js:
 *
 * `--tables` is a single global flag. `rows` gives labeled-paragraph items,
 * which are what you want for nearly every table here — a two-column
 * term/explanation table reads better as paragraphs in a narrow FedWiki column,
 * and a markdown item is editable in the wiki. `html` gives a real <table>,
 * which is only right for genuinely grid-shaped data, and is painful to edit.
 *
 * The manual has exactly one table of the second kind: the Shewhart constants
 * in section 16, where the whole point is scanning down a column. So this
 * script runs the converter BOTH ways and splices the html item for that one
 * table into the otherwise-rows bundle.
 *
 * The <table> markup is generated by the converter, not hand-written. The only
 * thing added here is inline styling, because FedWiki applies no table CSS of
 * its own and an unstyled grid is unreadable in a narrow column.
 *
 * To make another table grid-shaped, add an entry to AS_HTML below.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CONV = path.join(ROOT, '.claude/skills/fedwiki-page/scripts/md-to-fedwiki-page.js');
const SRC  = ['tools/rcn-spc-intro.md', 'tools/rcn-spc-manual.md'].map(p => path.join(ROOT, p));
const OUT  = path.join(ROOT, 'tools/rcn-spc-fedwiki-import.json');
const TITLE = 'Import Process Behavior Charts';

/** Tables to carry over as real <table> items, matched in both builds. */
const AS_HTML = [
  {
    what:        'Shewhart constants (manual §16)',
    page:        /manual/,
    rowsPrefix:  '**n:**',      // every labeled paragraph the rows build made
    htmlContains: '<th>n</th>', // the html item the html build made
  },
];

/** Minimal styling — FedWiki ships no table CSS, so a bare grid is unreadable. */
const TABLE_CSS =
  'width:100%;border-collapse:collapse;font-size:13px;font-variant-numeric:tabular-nums';
const CELL_CSS = 'padding:4px 8px;border:1px solid #ddd;text-align:left';
const HEAD_CSS = CELL_CSS + ';background:#f4f4f4;font-weight:700';

function style(html) {
  return html
    .replace(/<table>/g, `<table style="${TABLE_CSS}">`)
    .replace(/<th>/g, `<th style="${HEAD_CSS}">`)
    .replace(/<td>/g, `<td style="${CELL_CSS}">`);
}

/**
 * A paragraph consisting only of {{CHART:name}} is replaced by an html item
 * holding tools/spc-charts/<name>.svg. FedWiki renders html items raw, so the
 * chart arrives as a real picture rather than a link to one, and the page
 * carries no external asset. The SVGs are generated, not hand-drawn — see the
 * generator that writes them.
 */
const CHART_RE = /^\{\{CHART:([a-z0-9-]+)\}\}$/i;

function injectCharts(pages) {
  for (const [slug, pg] of Object.entries(pages)) {
    pg.story = pg.story.map(item => {
      const m = CHART_RE.exec((item.text || '').trim());
      if (!m) return item;
      const file = path.join(ROOT, 'tools/spc-charts', `${m[1]}.svg`);
      if (!fs.existsSync(file)) throw new Error(`missing chart: ${path.relative(ROOT, file)}`);
      console.log(`${slug}: inlined chart ${m[1]}.svg`);
      return { type: 'html', id: item.id, text: fs.readFileSync(file, 'utf8').trim() };
    });
  }
}

function build(mode) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `spcfw-${mode}-`));
  const out = path.join(dir, 'bundle.json');
  execFileSync('node', [CONV, ...SRC, '--bundle', out, '--bundle-title', TITLE,
                        '--tables', mode], { stdio: 'pipe' });
  return JSON.parse(fs.readFileSync(out, 'utf8'));
}

const pagesOf = b => b.story.find(i => i.type === 'importer').pages;

const rowsB = build('rows');
const htmlB = build('html');
const rows = pagesOf(rowsB), html = pagesOf(htmlB);

for (const spec of AS_HTML) {
  const slug = Object.keys(rows).find(s => spec.page.test(s));
  if (!slug) throw new Error(`no page matching ${spec.page} for: ${spec.what}`);

  const story = rows[slug].story;
  const first = story.findIndex(i => (i.text || '').startsWith(spec.rowsPrefix));
  if (first < 0) throw new Error(`no rows item starting "${spec.rowsPrefix}" for: ${spec.what}`);
  let last = first;
  while (last + 1 < story.length && (story[last + 1].text || '').startsWith(spec.rowsPrefix)) last++;

  const source = html[slug].story.find(
    i => i.type === 'html' && (i.text || '').includes(spec.htmlContains));
  if (!source) throw new Error(`no html item containing "${spec.htmlContains}" for: ${spec.what}`);

  story.splice(first, last - first + 1,
               { type: 'html', id: source.id, text: style(source.text) });
  console.log(`${spec.what}: replaced ${last - first + 1} paragraph items with one html table`);
}

injectCharts(rows);

fs.writeFileSync(OUT, JSON.stringify(rowsB, null, 2) + '\n');

// Each page also written on its own, so one can be re-imported without
// offering the other — re-importing a page that has already been edited in
// the wiki is how careful edits get overwritten.
const pageDir = path.join(ROOT, 'tools/fedwiki-pages');
fs.mkdirSync(pageDir, { recursive: true });
for (const [slug, pg] of Object.entries(rows)) {
  const single = { title: pg.title, story: pg.story, journal: [] };
  fs.writeFileSync(path.join(pageDir, `${slug}.json`), JSON.stringify(single, null, 2) + '\n');
  console.log('wrote', path.relative(ROOT, path.join(pageDir, `${slug}.json`)));
}
for (const [slug, pg] of Object.entries(rows)) {
  const kinds = pg.story.reduce((a, i) => (a[i.type] = (a[i.type] || 0) + 1, a), {});
  console.log(`${slug}: ${pg.story.length} items`,
              Object.entries(kinds).map(([k, v]) => `${k} ${v}`).join(', '));
}
console.log('wrote', path.relative(ROOT, OUT));
